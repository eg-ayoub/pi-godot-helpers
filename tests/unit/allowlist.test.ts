describe("tokenize", () => {
	it("splits words, quotes and pipes", () => {
		expect(tokenize(`grep -rn 'a b' "c d" e\\ f | wc -l`)).toEqual({ ok: true, pipeline: [["grep", "-rn", "a b", "c d", "e f"], ["wc", "-l"]] });
	});
	it("keeps backslashes inside double quotes except before special characters", () => {
		expect(tokenize(`grep "a\\.b\\"c"`)).toEqual({ ok: true, pipeline: [["grep", 'a\\.b"c']] });
	});
	it("treats adjacent quoted parts as one word", () => {
		expect(tokenize(`echo 'a'"b"c`)).toEqual({ ok: true, pipeline: [["echo", "abc"]] });
	});
});

describe("allowlist", () => {
	it.each(ALLOWED)("allows: %s", (command) => {
		const r = checkCommand(command, DEFAULT_ALLOWLIST);
		expect(r.ok ? "ok" : r.reason).toBe("ok");
	});

	it.each(REFUSED)("refuses: %s", (command, why) => {
		const r = checkCommand(command, DEFAULT_ALLOWLIST);
		expect(r.ok).toBe(false);
		if (!r.ok && why) expect(r.reason).toMatch(why);
	});

	it("allows configured extra commands and make targets", () => {
		const opts = { makeTargets: ["lint"], extraCommands: ["shellcheck"] };
		expect(checkCommand("shellcheck x.sh", opts).ok).toBe(true);
		expect(checkCommand("make lint", opts).ok).toBe(true);
		expect(checkCommand("make check-docs", opts).ok).toBe(false);
	});

	it("has a substantial table", () => {
		expect(ALLOWED.length + REFUSED.length).toBeGreaterThanOrEqual(150);
	});
});
